import { chromium, expect } from "@playwright/test";
import { randomUUID } from "node:crypto";
const base = process.env.TEST_BASE_URL;
if (!base || !["localhost", "127.0.0.1"].includes(new URL(base).hostname)) throw new Error("Use a local disposable database and TEST_BASE_URL");
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined, headless: true, args: ["--no-sandbox"] });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await page.goto(`${base}/login`);
  await page.getByRole("button", { name: "New here? Create an account" }).click();
  await page.getByLabel("Your name").fill("UI Test Owner");
  await page.getByLabel("Email address").fill(`ui-${randomUUID()}@example.test`);
  await page.getByLabel("Password", { exact: true }).fill(`pw-${randomUUID()}`);
  await page.getByRole("button", { name: "Create account", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Welcome, UI" })).toBeVisible();
  await page.getByRole("link", { name: "Application script", exact: true }).click();
  await page.getByRole("button", { name: "New module" }).click();
  await page.getByLabel("Module name").fill("Authentication");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(page.locator(".tree-title").filter({ hasText: "Authentication" })).toBeVisible();
  await page.getByRole("button", { name: "+", exact: true }).click();
  await page.getByLabel("Page name").fill("Login");
  await page.getByLabel("Route", { exact: true }).fill("/login");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await page.getByRole("button", { name: "+ Section", exact: true }).click();
  await page.getByLabel("Section title").fill("Sign-in form");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await page.getByLabel("Objective").fill("Authenticate users securely");
  await page.locator('select[name="status"]').selectOption("APPROVED");
  await page.getByRole("button", { name: "Save revision" }).click();
  await expect(page.getByText("Revision 2", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Create task", exact: true }).click();
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await page.getByRole("link", { name: "Tasks", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Sign-in form" })).toBeVisible();
  await page.getByRole("button", { name: "Claim task" }).click();
  await expect(page.getByRole("button", { name: "Request review" })).toBeVisible();
  await page.getByRole("link", { name: "Settings", exact: true }).click();
  await page.getByLabel("Project name").fill("UI persistence verified");
  await page.getByRole("button", { name: "Save settings" }).click();
  await expect(page.getByRole("status")).toHaveText("Saved successfully");
  await page.reload();
  await expect(page.getByLabel("Project name")).toHaveValue("UI persistence verified");
  await page.getByRole("link", { name: "Tasks", exact: true }).click();
  await expect(page.getByRole("button", { name: "Request review" })).toBeVisible();
  console.log("Browser smoke passed: account creation, hierarchy editing, approval, task creation and claiming, settings save and reload persistence.");
} finally { await browser.close(); }
