import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";

const base = process.env.TEST_BASE_URL;
if (!base || !["127.0.0.1", "localhost"].includes(new URL(base).hostname)) {
  throw new Error("Set TEST_BASE_URL to a local server connected to a disposable test database.");
}
const suffix = randomUUID();
const password = `test-${randomUUID()}`;
let cookie = "";
async function request(path, body, expected = 200, session = cookie) {
  const response = await fetch(base + path, { method: body === undefined ? "GET" : "POST", headers: { "Content-Type": "application/json", Cookie: session }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
  const result = await response.json();
  assert.equal(response.status, expected, `${path}: ${JSON.stringify(result)}`);
  return { response, data: result.data };
}
await request("/api/projects", undefined, 401);
const registered = await request("/api/auth/register", { name: "Database Test Owner", email: `owner-${suffix}@example.test`, password });
cookie = registered.response.headers.get("set-cookie").split(";")[0];
const projectId = registered.data.projectId;
const items = `/api/projects/${projectId}/items`;
const createdProject = (await request("/api/projects", { name: "Persistence test", description: "Stored in PostgreSQL" }, 201)).data;
assert((await request("/api/projects")).data.some(p => p.id === createdProject.id));
const outsider = await request("/api/auth/register", { name: "Other Owner", email: `other-${suffix}@example.test`, password }, 200, "");
const otherCookie = outsider.response.headers.get("set-cookie").split(";")[0];
await request(`/api/projects/${projectId}`, undefined, 404, otherCookie);
await request(items, { kind: "module", name: "Forbidden" }, 404, otherCookie);
const productModule = (await request(items, { kind: "module", name: "Authentication" })).data;
const page = (await request(items, { kind: "page", moduleId: productModule.id, name: "Login", route: "/login" })).data;
const section = (await request(items, { kind: "section", pageId: page.id, title: "Login form" })).data;
await request(items, { kind: "spec", id: section.id, version: 1, objective: "Authenticate", actions: "Sign in", rules: "Secure session", criteria: "Credentials are checked", status: "APPROVED" });
await request(items, { kind: "spec", id: section.id, version: 1, objective: "Stale edit", actions: "", rules: "", criteria: "", status: "DRAFT" }, 409);
const task = (await request("/api/tasks", { projectId, sectionId: section.id, title: "Implement login", priority: "HIGH" }, 201)).data;
assert.equal(task.status, "READY");
await request(`/api/tasks/${task.id}/claim`, {}, 404, otherCookie);
const claims = await Promise.all([1,2].map(() => fetch(base + `/api/tasks/${task.id}/claim`, { method: "POST", headers: { Cookie: cookie, "Content-Type": "application/json" }, body: "{}" })));
assert.deepEqual(claims.map(r => r.status).sort(), [200,409]);
await request(`/api/tasks/${task.id}/transition`, { to: "CODE_REVIEW" });
await request(`/api/tasks/${task.id}/transition`, { to: "QA", hasPullRequest: true }, 409);
await request(items, { kind: "pr", taskId: task.id, branch: "feature/login", prUrl: "https://github.com/example/project/pull/1" });
await request(`/api/tasks/${task.id}/transition`, { to: "QA" });
await request(`/api/tasks/${task.id}/transition`, { to: "DONE", testsPassed: true, qaAccepted: true }, 409);
const test = (await request(items, { kind: "test", taskId: task.id, title: "Successful login", steps: "Enter valid credentials", expectedResult: "Session created" })).data;
await request(items, { kind: "run", id: test.id, status: "PASSED", notes: "Verified against development database" });
await request(items, { kind: "accept", taskId: task.id, accepted: true });
await request(`/api/tasks/${task.id}/transition`, { to: "DONE" });
const bug = (await request(items, { kind: "bug", title: "Test issue", severity: "LOW", reproductionSteps: "Example reproduction" })).data;
await request(items, { kind: "bugStatus", id: bug.id, status: "VERIFIED" });
const snapshot = (await request(`/api/projects/${projectId}`)).data;
assert.equal(snapshot.tasks.find(t => t.id === task.id).status, "DONE");
assert.equal(snapshot.modules[0].pages[0].sections[0].version, 2);
assert.equal(snapshot.bugs[0].status, "VERIFIED");
assert(snapshot.activity.length >= 8);
const settings = { name: "Updated workspace", description: "Persisted settings", stack: "Next.js and PostgreSQL", repositoryUrl: "https://github.com/example/project", developmentRules: "Test each change" };
const updated = await fetch(base + `/api/projects/${projectId}`, { method: "PATCH", headers: { Cookie: cookie, "Content-Type": "application/json" }, body: JSON.stringify(settings) });
assert.equal(updated.status, 200);
assert.equal((await request(`/api/projects/${projectId}`)).data.name, "Updated workspace");
await request(items, { kind: "member", email: `other-${suffix}@example.test`, role: "DEVELOPER" });
await request(`/api/projects/${projectId}`, undefined, 200, otherCookie);
await request(items, { kind: "spec", id: section.id, version: 2, objective: "Forbidden approval", actions: "", rules: "", criteria: "", status: "APPROVED" }, 403, otherCookie);
const forbiddenSettings = await fetch(base + `/api/projects/${projectId}`, { method: "PATCH", headers: { Cookie: otherCookie, "Content-Type": "application/json" }, body: JSON.stringify(settings) });
assert.equal(forbiddenSettings.status, 403);
const wrongOrigin = await fetch(base + items, { method: "POST", headers: { Cookie: cookie, Origin: "https://attacker.example", "Content-Type": "application/json" }, body: JSON.stringify({ kind: "module", name: "Forbidden" }) });
assert.equal(wrongOrigin.status, 403);
await request("/api/auth/logout", {});
await request("/api/projects", undefined, 401);
const signedIn = await request("/api/auth/login", { email: `owner-${suffix}@example.test`, password }, 200, "");
cookie = signedIn.response.headers.get("set-cookie").split(";")[0];
assert.equal((await request(`/api/projects/${projectId}`)).data.tasks[0].status, "DONE");
console.log("Database smoke test passed: authentication, isolation, settings persistence, role permissions, revision conflicts, atomic claims, QA gates, bugs, audit logs, and session revocation.");
